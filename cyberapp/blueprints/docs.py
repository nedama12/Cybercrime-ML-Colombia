"""Public pages: PGC project overview and CRISP-ML documentation."""
from flask import Blueprint, abort, current_app, render_template, send_from_directory

from ..content import PHASES
from ..ml.service import get_model_service

bp = Blueprint("docs", __name__)


@bp.route("/")
def home():
    return render_template("index.html")


@bp.route("/phases/<slug>")
def phase(slug):
    index = next((i for i, p in enumerate(PHASES) if p["slug"] == slug), None)
    if index is None:
        abort(404)
    current = PHASES[index]
    return render_template(
        # A phase without its own template yet falls back to a "being documented" page.
        [f"phases/phase-{current['number']}.html", "phases/pending.html"],
        phase=current,
        prev_phase=PHASES[index - 1] if index > 0 else None,
        next_phase=PHASES[index + 1] if index < len(PHASES) - 1 else None,
        # Phases 3 and 4 show the results of the deployed model, so the published
        # documentation always matches the model used by the system.
        model_meta=get_model_service().metadata,
    )


@bp.route("/figures/<path:filename>")
def figure(filename):
    """Serve the EDA figures generated by the analysis scripts (single source of truth)."""
    return send_from_directory(current_app.config["FIGURES_DIR"], filename)
